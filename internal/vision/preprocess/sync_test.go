var update = flag.Bool("update", false, "rewrite testdata/geometry_sync.json from the Go implementation")

// geometryCase is one row of testdata/geometry_sync.json: the tensor shape and Meta a spec gives
// for an image size. clients/python/tests/test_go_python_sync.py checks the converter's
// reference implementation (reference.apply_spec) against the same rows, so both sides compute
// the same geometry for every mode — the pixels themselves differ only by the resampler (PIL vs
// imaging), which tier B1 measures.
type geometryCase struct {
	Spec  map[string]any  `json:"spec"`
	Image [2]int          `json:"image"`
	Shape []int64         `json:"shape"`
	Meta  preprocess.Meta `json:"meta"`
}

// geometrySpecs are written in the manifest block's vocabulary (what Python reads).
