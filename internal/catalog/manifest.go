// generatedHeader opens every manifest RenderManifest writes. Pull uses it to tell a manifest it
// generated (safe to regenerate when the catalog changes) from one a user wrote or edited.
//
// The header line also records a hash of the body below it ("[body <hex>]"). A file whose body
// still hashes to its own recorded value is untouched catalog output and may be regenerated; a
// file whose body no longer matches was edited by hand — even if the editor kept the header —
// and is kept. Manifests written before the hash existed carry none and are treated as generated.
//
// The scheme is independent of HOW the body was rendered: a manifest written by an older release
// (whose hand-built renderer formatted the body differently) still matches its own recorded hash,
// so it is recognised as generated and regenerated. Keep the header format and bodyHash stable.
const generatedHeader = "# Generated by `visionserve pull"

// bodyHashRE finds the recorded body hash in a generated header line.
var bodyHashRE = regexp.MustCompile(`\[body ([0-9a-f]{16})\]`)

// bodyHash is the short content hash RenderManifest records for the manifest body. 64 bits is
// plenty to notice an edit; it is not a security control (the weights' sha256 is).
func bodyHash(body string) string {
	sum := sha256.Sum256([]byte(body))
	return hex.EncodeToString(sum[:8])
}

// isUneditedGenerated reports whether content is a manifest RenderManifest produced (for any
// catalog version) that nobody has edited since: it starts with generatedHeader and its body still
// matches the hash the header recorded. Old generated manifests without a recorded hash count as
// unedited, which is how they were treated before the hash existed.
func isUneditedGenerated(content string) bool {
	if !strings.HasPrefix(content, generatedHeader) {
		return false
	}
	nl := strings.IndexByte(content, '\n')
	if nl < 0 {
		return true
	}
	m := bodyHashRE.FindStringSubmatch(content[:nl])
	if m == nil {
		return true // pre-hash generated manifest
	}
	return m[1] == bodyHash(content[nl+1:])
}

// RenderManifest produces the YAML content for <modelsdir>/<name>/manifest.yaml: a header line
// (generatedHeader + the body hash), the entry's description / unverified-source warning as
// comments, then the manifest itself, marshalled by yaml.v3 from a manifestDoc. Marshalling a
// schema-shaped value rather than concatenating strings is what keeps a field in its block: the
// hand-built renderer could write box_format or text_threshold under input: (where the loader
// silently ignores them) whenever no postprocess header had been emitted.
func (e Entry) RenderManifest() (string, error) {
	body, err := e.renderManifestBody()
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("%s %s` [body %s] — hand edits are kept on re-pull (--force regenerates).\n%s",
		generatedHeader, e.Name, bodyHash(body), body), nil
}

// renderManifestBody is everything below RenderManifest's header line.
func (e Entry) renderManifestBody() (string, error) {
	var b strings.Builder
	if e.Description != "" {
		b.WriteString(commentLines(e.Description))
	}
	if !e.Verified {
		b.WriteString(commentLines("WARNING: pulled from an unverified HF source. " + e.Note))
	}
	var y bytes.Buffer
	enc := yaml.NewEncoder(&y)
	enc.SetIndent(2)
	if err := enc.Encode(e.manifestDoc()); err != nil {
		return "", fmt.Errorf("catalog: render manifest for %s: %w", e.Name, err)
	}
	if err := enc.Close(); err != nil {
		return "", fmt.Errorf("catalog: render manifest for %s: %w", e.Name, err)
	}
	b.WriteString(spaceBlocks(y.String()))
	return b.String(), nil
}

// manifestDoc is the generated manifest.yaml: the subset of registry.Manifest a catalog entry can
// set, with the same yaml keys in the same blocks, in the order the file shows them. It mirrors
// registry.Manifest by hand because that type carries no omitempty tags (marshalling it would
// write every unset field as a zero) and its sha256 field cannot be built outside the registry
// package. TestManifestDocMirrorsRegistrySchema fails if a key here is not a registry.Manifest key
// at the same path, and TestRenderManifestMatchesLegacyRenderer pins the parsed result.
type manifestDoc struct {
	Name    string `yaml:"name"`
	Task    string `yaml:"task"`
	License string `yaml:"license"`
	// source_url and sha256 are what turn "the manifest says Apache-2.0" into "these exact bytes
	// came from this audited upstream". The registry's verified mode refuses a model missing
	// either, so a pulled model has to carry both to be usable there.
	SourceURL    string            `yaml:"source_url,omitempty"`
	SHA256       any               `yaml:"sha256,omitempty"` // string (model_file) or role→digest map (files:)
	SHA256Files  map[string]string `yaml:"sha256_files,omitempty"`
	Architecture string            `yaml:"architecture,omitempty"`
	Detector     string            `yaml:"detector,omitempty"`
	Segmenter    string            `yaml:"segmenter,omitempty"`
	Files        map[string]string `yaml:"files,omitempty"`
	ModelFile    string            `yaml:"model_file,omitempty"`
	Input        inputDoc          `yaml:"input"`
	Preprocess   *preprocessDoc    `yaml:"preprocess,omitempty"`
	Postprocess  postprocessDoc    `yaml:"postprocess,omitempty"`
	Grasp        graspDoc          `yaml:"grasp,omitempty"`
	Explain      *explainDoc       `yaml:"explain,omitempty"`
	Instance     *instanceDoc      `yaml:"instance,omitempty"`
	Labels       string            `yaml:"labels,omitempty"`
	Runtime      runtimeDoc        `yaml:"runtime,omitempty"`
}

type inputDoc struct {
	Width  int    `yaml:"width"`
	Height int    `yaml:"height"`
	Layout string `yaml:"layout,omitempty"`
	// Always written, false included: squash vs letterbox is the first thing to check when a
	// model's accuracy is off (BUGS_TO_FIX.md #1).
	Letterbox  bool          `yaml:"letterbox"`
	Crop       string        `yaml:"crop,omitempty"`
	KeepAspect bool          `yaml:"keep_aspect,omitempty"`
	MultipleOf int           `yaml:"multiple_of,omitempty"`
	Normalize  *normalizeDoc `yaml:"normalize,omitempty"`
}

// preprocessDoc is the part of the manifest's `preprocess:` block an entry can set (registry
// PreprocessBlock); everything else stays in input.*.
type preprocessDoc struct {
	Resize   string  `yaml:"resize,omitempty"`
	CropPct  float32 `yaml:"crop_pct,omitempty"`
	Resample string  `yaml:"resample,omitempty"`
}

type normalizeDoc struct {
	Mean []float32 `yaml:"mean,flow"`
	Std  []float32 `yaml:"std,flow"`
}

type postprocessDoc struct {
	Type          string  `yaml:"type,omitempty"`
	BoxFormat     string  `yaml:"box_format,omitempty"`
	ConfThreshold float64 `yaml:"conf_threshold,omitempty"`
	TextThreshold float64 `yaml:"text_threshold,omitempty"`
	MaxDetections int     `yaml:"max_detections,omitempty"`
}

type graspDoc struct {
	GripperMin float64 `yaml:"gripper_min,omitempty"`
	GripperMax float64 `yaml:"gripper_max,omitempty"`
}

type explainDoc struct {
	Type          string            `yaml:"type"`
	Role          string            `yaml:"role,omitempty"`
	Outputs       map[string]string `yaml:"outputs,omitempty"`
	SpatialStride int               `yaml:"spatial_stride,omitempty"`
	TopChannels   int               `yaml:"top_channels,omitempty"`
}

type instanceDoc struct {
	MaxTemplates int     `yaml:"max_templates,omitempty"`
	SimThreshold float64 `yaml:"sim_threshold,omitempty"`
	PatchSize    int     `yaml:"patch_size,omitempty"`
}

type runtimeDoc struct {
	Prefer            []string       `yaml:"prefer,flow,omitempty"`
	IdleUnloadSeconds int            `yaml:"idle_unload_seconds,omitempty"`
	Threads           map[string]int `yaml:"threads,omitempty"`
}

// manifestDoc maps the entry onto the manifest schema.
func (e Entry) manifestDoc() manifestDoc {
	d := manifestDoc{
		Name:         e.Name,
		Task:         e.Task,
		License:      e.License,
		SourceURL:    e.SourceURL(),
		SHA256:       e.manifestSHA256(),
		SHA256Files:  e.manifestSHA256Files(),
		Architecture: e.Architecture,
		Detector:     e.Detector,
		Segmenter:    e.Segmenter,
		Labels:       e.LabelsFile,
	}
	// model_file (single-file) vs files: map (multi-session: the entry's own files, plus virtual
	// paths into sibling model directories).
	if mfs := e.manifestFiles(); len(e.VirtualFiles) > 0 || len(mfs) > 0 {
		d.Files = make(map[string]string, len(e.VirtualFiles)+len(mfs))
		for role, rel := range e.VirtualFiles {
			d.Files[role] = rel
		}
		for _, f := range mfs {
			d.Files[f.ManifestRole] = f.LocalFilename
		}
	} else {
		d.ModelFile = e.modelFile()
	}

	d.Input = inputDoc{
		Width: e.InputWidth, Height: e.InputHeight, Layout: e.InputLayout, Letterbox: e.Letterbox,
		Crop: e.Crop, KeepAspect: e.KeepAspect, MultipleOf: e.MultipleOf,
	}
	if e.Normalize != nil {
		d.Input.Normalize = &normalizeDoc{Mean: e.Normalize.Mean, Std: e.Normalize.Std}
	}
	if e.Resize != "" || e.CropPct != 0 || e.Resample != "" {
		d.Preprocess = &preprocessDoc{Resize: e.Resize, CropPct: e.CropPct, Resample: e.Resample}
	}
	d.Postprocess = postprocessDoc{
		Type: e.PostprocessType, BoxFormat: e.BoxFormat, ConfThreshold: e.ConfThreshold,
		TextThreshold: e.TextThreshold, MaxDetections: e.MaxDetections,
	}
	d.Grasp = graspDoc{GripperMin: e.GripperMin, GripperMax: e.GripperMax}
	if x := e.Explain; x != nil {
		d.Explain = &explainDoc{Type: x.Type, Role: x.Role, Outputs: x.Outputs,
			SpatialStride: x.SpatialStride, TopChannels: x.TopChannels}
	}
	if in := e.Instance; in != nil {
		d.Instance = &instanceDoc{MaxTemplates: in.MaxTemplates, SimThreshold: in.SimThreshold, PatchSize: in.PatchSize}
	}
	d.Runtime = runtimeDoc{Prefer: e.RuntimePrefer, IdleUnloadSeconds: e.IdleUnloadSeconds,
		Threads: e.RuntimeThreads}
	return d
}

// composed reports whether the entry downloads nothing and only wires together files its
// dependencies own (grounded-sam): its manifest declares no pins and no source of its own.
func (e Entry) composed() bool { return len(e.VirtualFiles) > 0 && len(e.Files) == 0 }

// blockKeys are the top-level keys the generated file sets off with a blank line, for reading.
var blockKeys = map[string]bool{
	"files": true, "input": true, "preprocess": true, "postprocess": true, "grasp": true, "explain": true,
	"instance": true, "labels": true, "runtime": true,
}

// spaceBlocks inserts a blank line before each top-level key in blockKeys. Only column-0 lines
// are considered: in yaml.v3's block output those are always top-level keys (nested keys and the
// continuation lines of a scalar are indented), so a blank line never lands inside a value.
func spaceBlocks(doc string) string {
	var b strings.Builder
	for i, line := range strings.SplitAfter(doc, "\n") {
		if i > 0 && line != "" && line[0] != ' ' && line[0] != '#' {
			if k, _, ok := strings.Cut(line, ":"); ok && blockKeys[k] {
				b.WriteByte('\n')
			}
		}
		b.WriteString(line)
	}
	return b.String()
}

// commentLines renders text as YAML comment lines, "# " before each line, so a description that
// holds a newline cannot break out of the comment into the document.
func commentLines(text string) string {
	var b strings.Builder
	for _, line := range strings.Split(strings.TrimRight(text, "\n"), "\n") {
		b.WriteString(strings.TrimRight("# "+line, " "))
		b.WriteByte('\n')
	}
	return b.String()
}

// SourceURL is the audited upstream this entry's weights come from. Derived rather than
// stored, so it cannot drift from HFRepo. The trailing slash matters: registry's ledger and
// verified-source allowlist both match by URL prefix, and the ledger records repo roots in
// exactly this form. Entries served from DirectURL have no single canonical repo page, so
// they get no source_url and stay outside verified mode until one is recorded by hand.
//
// An entry with HFSubdir gets that folder's page ("https://huggingface.co/<repo>/tree/main/<dir>/"),
// which still starts with the repo root, so a ledger record for the whole repo covers it unless a
// longer record for the folder says otherwise.
func (e Entry) SourceURL() string {
	if e.HFRepo == "" {
		return ""
	}
	if e.HFSubdir != "" {
		return "https://huggingface.co/" + e.HFRepo + "/tree/main/" + strings.Trim(e.HFSubdir, "/") + "/"
	}
	return "https://huggingface.co/" + e.HFRepo + "/"
}

// manifestSHA256 is the manifest `sha256:` value, or nil when nothing is pinned. The shape
// mirrors what registry.SHA256Field parses: a digest string for a single-file model, a
// role→digest map for a multi-session one. Side files that carry no ManifestRole (external data,
// a vocab) are not in the manifest's `files:` map; their pins go in `sha256_files:`
// (manifestSHA256Files).
//
// A partly composed entry (own Files + VirtualFiles) pins its own files only: the files it
// borrows are pinned by the dependency that owns them, and verified mode admits them through that
// dependency (registry verifyWeights).
func (e Entry) manifestSHA256() any {
	if e.composed() {
		return nil // composed model: the pins live in the dependencies it references
	}
	if mf := e.modelFile(); mf != "" && len(e.VirtualFiles) == 0 {
		for _, f := range e.Files {
			if f.LocalFilename == mf && f.SHA256 != "" {
				return f.SHA256
			}
		}
		return nil
	}
	pins := map[string]string{}
	for _, f := range e.manifestFiles() {
		if f.SHA256 != "" {
			pins[f.ManifestRole] = f.SHA256
		}
	}
	if len(pins) == 0 {
		return nil
	}
	return pins
}

// manifestSHA256Files is the manifest `sha256_files:` map: the pins of pinned files that are not
// ONNX sessions (no ManifestRole, not the single model_file) — ONNX external weight data,
// tokenizers, labels. Without it those bytes were checked once at download and never again; with
// it the registry re-verifies them at load like the session weights. nil when there are none.
func (e Entry) manifestSHA256Files() map[string]string {
	if e.composed() {
		return nil
	}
	mf := e.modelFile()
	if len(e.VirtualFiles) > 0 {
		mf = "" // files: map, never model_file (manifestDoc)
	}
	var side map[string]string
	for _, f := range e.Files {
		if f.SHA256 != "" && f.ManifestRole == "" && f.LocalFilename != mf {
			if side == nil {
				side = map[string]string{}
			}
			side[f.LocalFilename] = f.SHA256
		}
	}
	return side
}

// manifestFiles returns the files that should appear in the manifest `files:` map.
func (e Entry) manifestFiles() []File {
	var out []File
	for _, f := range e.Files {
		if f.ManifestRole != "" {
			out = append(out, f)
		}
	}
	return out
}

// modelFile returns the single model_file local name when the entry is
// single-session (exactly one file, no ManifestRole used).
func (e Entry) modelFile() string {
	if len(e.manifestFiles()) > 0 {
		return ""
	}
	for _, f := range e.Files {
		if f.Role == "model" {
			return f.LocalFilename
		}
	}
	if len(e.Files) == 1 {
		return e.Files[0].LocalFilename
	}
	return ""
}
